"""Preserve supplied fav1 API bytes; generate identities without compiling Java."""
import argparse, hashlib, json, shutil
from pathlib import Path

def describe(root):
    files={p.relative_to(root).as_posix():hashlib.sha256(p.read_bytes()).hexdigest() for p in root.rglob('*.class')}
    if not files:raise ValueError('API set has no classes: '+str(root))
    digest=hashlib.sha256()
    for name,value in sorted(files.items()):digest.update(name.encode('utf-8')+b'\0'+bytes.fromhex(value))
    return {'id':digest.hexdigest(),'files':dict(sorted(files.items()))}

def prepare(source,baseline):
    original=baseline/'romfs/classes';legacy=source/'romfs/api-legacy-fit37-fav1'
    expected=describe(original)
    # This is an immutable import, never a refresh from the candidate API.
    if legacy.exists():
        if describe(legacy)!=expected:raise ValueError('legacy API differs; refusing to overwrite')
    else:shutil.copytree(original,legacy)
    active=describe(source/'romfs/classes')
    result={'schema':1,'legacy':dict(expected,directory='api-legacy-fit37-fav1'),'active':dict(active,directory='classes')}
    path=source/'romfs/api-sets.json';path.write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
    header=source/'src/api_sets_generated.h'
    header.write_text('#pragma once\n// Generated by prepare_api_sets.py; legacy class bytes must never be recompiled.\n'
        'namespace api_sets {\ninline constexpr const char* legacy_id="'+expected['id']+'";\n'
        'inline constexpr const char* active_id="'+active['id']+'";\n}\n',encoding='utf-8')
    print('API sets:',len(expected['files']),'legacy classes;',len(active['files']),'active classes')

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--source',type=Path,required=True);p.add_argument('--baseline',type=Path,required=True)
    args=p.parse_args();prepare(args.source.absolute(),args.baseline.absolute())
