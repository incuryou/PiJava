import json,re,sys
inv=json.load(open('/workspace/j2me-p2-1a/GLOBALS-INVENTORY.json'))['globals']
MOD=[('Other','Diagnostics','diag'),('NativeRegistry','NativeRegistry','natives'),
     ('ClassLoader/Resolver','ClassLoader','classes'),('Heap/RootScope','Heap','heap'),
     ('ExecutionContext/Scheduler','Execution','exec'),('PlatformHost','PlatformHost','platform'),
     ('RenderSurface','RenderSurface','render')]
sel=[];excl=[]
seen=set()
for x in inv:
    key=(x['name'])
    if x['scope'] not in ('file','namespace'): excl.append((x,'scope='+x['scope']+'（函数内static/静态成员不可从文件尾引用，或为编译期常量）'));continue
    if x['mutability']=='immutable-constant': excl.append((x,'编译期/只读常量，无运行期状态'));continue
    if 'third_party' in x['file']: excl.append((x,'第三方 stb_image 内部状态，不属 VM'));continue
    if key in seen: continue
    seen.add(key); sel.append(x)
def fld(n): return re.sub(r'\W','_',n.replace('::','__'))
out=[]
w=out.append
w('// vm_state.h — P2.1-b VMState facade (generated by tools/gen_vmstate.py from P2.1-a GLOBALS-INVENTORY.json).')
w('// Facade ONLY: every field is an lvalue reference bound to the pre-existing global.')
w('// No storage is moved, no global is removed, no call site is changed.')
w('// Included at the very end of j2mevm.cpp (always, P2.1 final).')
w('#pragma once')
w('#include <memory>')
w('namespace j2me_vmstate {')
cnt={}
for m,sn,fn in MOD:
    items=[x for x in sel if x['module']==m]; cnt[m]=len(items)
    w(f'struct {sn}State {{  // module: {m}, {len(items)} fields')
    for x in items:
        g='__SWITCH__' if x['configs']==['switch'] else None
        if g: w('#ifdef __SWITCH__')
        w(f'    decltype((::{x["name"]})) {fld(x["name"])};  // {x["file"]}:{x["line"]}')
        if g: w('#endif')
    w('};')
w('struct VMState {')
for m,sn,fn in MOD: w(f'    {sn}State {fn};')
w('};')
w('inline constexpr VMState kVMState{')
for m,sn,fn in MOD:
    items=[x for x in sel if x['module']==m]
    w(f'    /* {fn} */ {{')
    for x in items:
        g=x['configs']==['switch']
        if g: w('#ifdef __SWITCH__')
        w(f"        ::{x['name']},")
        if g: w('#endif')
    w('    },')
w('};')
w('// Accessor: the single entry point P2.1-c will migrate behind.')
w('constexpr const VMState& vm_state() { return kVMState; }')
w('// Address identity: each facade field IS the old global (same object, same address).')
for m,sn,fn in MOD:
    for x in [x for x in sel if x['module']==m]:
        g=x['configs']==['switch']
        if g: w('#ifdef __SWITCH__')
        w(f'static_assert(std::addressof(kVMState.{fn}.{fld(x["name"])}) == std::addressof(::{x["name"]}), "VMState.{fn}.{fld(x["name"])} must alias {x["name"]}");')
        if g: w('#endif')
w('// Field-count bookkeeping (desktop / switch)')
nd=sum(1 for x in sel if x['configs']!=['switch'])
w(f'constexpr int kFacadeFieldsDesktop = {nd};')
w(f'constexpr int kFacadeFieldsSwitch = {len(sel)};')
w('}  // namespace j2me_vmstate')
open(sys.argv[1],'w').write('\n'.join(out)+'\n')
json.dump({'selected':[{'name':x['name'],'module':x['module'],'file':x['file'],'line':x['line'],'configs':x['configs']} for x in sel],
  'excluded':[{'name':x['name'],'scope':x['scope'],'file':x['file'],'line':x['line'],'reason':r} for x,r in excl],
  'counts':cnt,'desktop_fields':nd,'switch_fields':len(sel)},open(sys.argv[2],'w'),ensure_ascii=False,indent=1)
print(cnt,nd,len(sel),len(excl))
